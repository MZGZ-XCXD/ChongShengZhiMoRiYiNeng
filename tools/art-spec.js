const KINDS = {
    portraits: { size: '3:4', w: 768, h: 1024, ext: '.png', bg: '背景虚化，不要出现第二个人' },
    scenes: { size: '16:9', w: 1280, h: 720, ext: '.jpg', bg: '横幅构图，画面里不要出现人' },
    dooms: { size: '16:9', w: 1280, h: 720, ext: '.jpg', bg: '横幅构图，只有环境，不要出现人' },
};

function briefsFor(kind) {
    if (kind === 'portraits') return PORTRAITS;
    if (kind === 'scenes') return SCENES;
    return DOOMS;
}

/* 一条完整的出图提示词 */
function buildPrompt(kind, id, name) {
    const kindCfg = KINDS[kind];
    const brief = briefsFor(kind)[id];
    if (!brief) return null;
    const head = kind === 'portraits'
        ? '用途：末日生存游戏的羁绊角色立绘（胸像近景；游戏内既放大展示，也会缩到 68×88 的小卡片里）。'
        : (kind === 'scenes' ? '用途：末日生存游戏的地点背景图（横幅，界面里会压一层暗色渐变并叠上地点名）。'
            : '用途：末日生存游戏的末日氛围图（横幅）。');
    const framing = kind === 'portraits'
        ? '构图：竖构图 3:4，胸像近景（头顶到胸口），人物略偏左，右侧留一块相对干净的暗部给名字与数值。'
        : '构图：横幅 16:9，空旷场景，视角接近人眼高度，' + kindCfg.bg + '。';
    const tail = name ? '画面里不要出现任何文字、logo 或界面元素（这张对应「' + name + '」）。' : '';
    /* 立绘用通用段（已经写完长相/构图/光线/质感/禁止），不再重复拼风格段 */
    if (kind === 'portraits') {
        return [head, '主体：' + brief, PORTRAIT_COMMON,
            '色彩：' + STYLE.palette, tail].filter(Boolean).join('\n');
    }
    return [head, '主体：' + brief, '画风：' + STYLE.medium, framing,
        '光线与氛围：' + STYLE.lighting, '色彩：' + STYLE.palette, '质感：' + STYLE.texture,
        '禁止：' + STYLE.avoid + '。', tail].filter(Boolean).join('\n');
}

function all() {
    const out = [];
    for (const kind of ['portraits', 'scenes', 'dooms']) {
        const briefs = briefsFor(kind);
        for (const id in briefs) {
            out.push({
                kind: kind, id: id,
                path: 'assets/' + kind + '/' + id + KINDS[kind].ext,
                aspect: KINDS[kind].size, width: KINDS[kind].w, height: KINDS[kind].h,
                prompt: buildPrompt(kind, id, id),
            });
        }
    }
    return out;
}

module.exports = { STYLE, KINDS, PORTRAITS, SCENES, DOOMS, buildPrompt, all, briefsFor };
